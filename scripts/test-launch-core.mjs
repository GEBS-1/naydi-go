import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdirSync} from 'node:fs';
mkdirSync('artifacts/launch',{recursive:true});
await build({stdin:{contents:"export * from './lib/shopping-list';export * from './lib/location-context';export * from './lib/personal';export * from './lib/request-body';",resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',outfile:'artifacts/launch/core.mjs'});
const api=await import('../artifacts/launch/core.mjs');
assert.deepEqual(api.selectLocation({queryCity:'Самара',manual:'Москва',geolocation:'Казань'}),{city:'Самара',source:'query'});
assert.equal(api.selectLocation({manual:'Москва',geolocation:'Казань',ip:'Пермь'}).city,'Москва');
assert.equal(api.explicitCityCandidate('дрель в наличии'),null);
assert.equal(api.explicitCityCandidate('дрель в Самаре').value,'Самаре');
let items=api.itemsFromTask('дрель, свёрла, дюбели, уровень до 10000');assert.equal(items.length,4);
items[0].selected={id:'fixture',title:'Unit fixture',price:100,source:'https://example.org/item',checkedAt:'2026-09-29'};items[0].quantity=2;
assert.deepEqual(api.listTotal(items),{known:200,unknown:3});
items=api.refineItems(items,'убери уровень');assert.equal(items.length,3);
items=api.refineItems(items,'дрель уже есть');assert.deepEqual(api.listTotal(items),{known:0,unknown:2});
const data=api.emptyPersonal();data.favorites.push({id:'unit',title:'Fixture',kind:'product',url:'https://example.org',city:'Самара',price:null});
assert.equal(api.mergePersonal(data,data).favorites.length,1);
assert.equal(api.personalSchema.safeParse({...data,favorites:[{...data.favorites[0],url:'javascript:alert(1)'}]}).success,false);
assert.equal(new TextDecoder().decode(await api.limitedBody(new Request('https://example.org',{method:'POST',body:'ok'}),2)),'ok');
await assert.rejects(api.limitedBody(new Request('https://example.org',{method:'POST',body:'too big'}),2));
console.log('PASS: location precedence, city intent, list extraction/removal/quantities/known totals, merge dedup, unsafe URL rejection, streamed body limit. Unit fixtures, no real offers claimed.');
