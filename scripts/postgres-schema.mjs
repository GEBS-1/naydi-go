// Derive a PostgreSQL schema from an up-to-date SQLite snapshot, including constraints.
const quote=name=>'"'+name.replaceAll('"','""')+'"';
export function postgresSchema(sqlite){
 const tables=sqlite.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' AND name NOT LIKE 'd1_%' ORDER BY name").all().map(r=>r.name);
 const create=[],constraints=[],indexes=[];
 for(const table of tables){
  const fields=sqlite.prepare(`PRAGMA table_info(${quote(table)})`).all();
  const columns=fields.map(c=>`${quote(c.name)} ${/INT/i.test(c.type)?'BIGINT':'TEXT'}${c.notnull?' NOT NULL':''}${c.dflt_value!==null?' DEFAULT '+c.dflt_value:''}`);
  const pk=fields.filter(c=>c.pk).sort((a,b)=>a.pk-b.pk);if(pk.length)columns.push('PRIMARY KEY ('+pk.map(c=>quote(c.name)).join(',')+')');
  columns.push('rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE');
  create.push(`CREATE TABLE ${quote(table)} (${columns.join(',')});`);
  for(const fk of sqlite.prepare(`PRAGMA foreign_key_list(${quote(table)})`).all())constraints.push(`ALTER TABLE ${quote(table)} ADD FOREIGN KEY (${quote(fk.from)}) REFERENCES ${quote(fk.table)} (${quote(fk.to)});`);
  for(const index of sqlite.prepare(`PRAGMA index_list(${quote(table)})`).all()){
   if(index.origin==='pk')continue;
   const original=sqlite.prepare('SELECT sql FROM sqlite_master WHERE name=?').get(index.name)?.sql;
   if(original)indexes.push(original.replace(/`([^`]+)`/g,'"$1"')+';');
   else{const names=sqlite.prepare(`PRAGMA index_info(${quote(index.name)})`).all().map(c=>quote(c.name));indexes.push(`CREATE UNIQUE INDEX ${quote('unique_'+table+'_'+index.seq)} ON ${quote(table)} (${names.join(',')});`);}
  }
  // Nonnegative credits are part of the business contract.
  if(table==='buyer_grants')constraints.push('ALTER TABLE buyer_grants ADD CHECK (remaining>=0);');
 }
 return {tables,create,indexes,constraints};
}
